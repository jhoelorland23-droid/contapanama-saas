const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async ({ page, api, disk, doc, out, check, enableCorrectionServer }) => {
  const entries = () => disk().asientos_contables.filter(e => e.transaccion_id === doc.id);
  const original = entries()[0];
  const audits = () => disk().audit_events.filter(e => e.objeto_id === doc.id && e.accion === 'documento_corregido');
  await page.getByRole('button', { name: 'Diario Contable', exact: true }).click();
  await page.locator('input[type="month"]').fill('2025-03');
  await page.getByPlaceholder('Buscar concepto...').fill(doc.descripcion);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Journal controls must stay inside the desktop viewport');
  const row = page.getByRole('row').filter({ hasText: doc.descripcion });
  const open = row.getByRole('button', { name: 'Corregir documento', exact: true });
  await open.click();
  const dialog = page.getByRole('dialog', { name: 'Corregir documento', exact: true });
  const confirm = dialog.getByRole('button', { name: 'Confirmar correcci\u00f3n', exact: true });
  await dialog.getByRole('alert').waitFor();
  assert.equal(await confirm.count(), 0);
  assert.equal(entries().length, 1);
  enableCorrectionServer();
  await dialog.getByRole('button', { name: 'Actualizar documento', exact: true }).click();
  await confirm.waitFor();
  assert(await confirm.isDisabled());
  assert.equal(await dialog.getByLabel('Cambios propuestos').innerText(), 'Sin cambios');
  const reason = 'QA importe corregido contra soporte revisado';
  const change = async (amount, explanation) => {
    await dialog.getByLabel('Base corregida', { exact: true }).fill(String(amount));
    await dialog.getByLabel('Motivo de la correcci\u00f3n', { exact: true }).fill(explanation);
  };
  const consent = dialog.getByRole('checkbox', { name: 'Revis\u00e9 los cambios y autorizo la correcci\u00f3n del documento.', exact: true });
  await change(200, reason);
  assert(await confirm.isDisabled());
  await page.screenshot({ path: path.join(out, 'correccion-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  const bounds = await dialog.boundingBox();
  assert(bounds.x >= 0 && bounds.x + bounds.width <= 390);
  assert(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth));
  await confirm.scrollIntoViewIfNeeded();
  const buttonBounds = await confirm.boundingBox();
  assert(buttonBounds.y >= 0 && buttonBounds.y + buttonBounds.height <= 844);
  await page.screenshot({ path: path.join(out, 'correccion-mobile.png') });
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal(entries().length, 1);
  assert.equal(audits().length, 0);
  check('correction requires updated backend; reviewed values fit desktop/mobile and cancellation makes no changes');

  await page.setViewportSize({ width: 1440, height: 1050 });
  await open.click();
  await change(200, reason);
  await consent.check();
  await confirm.click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(entries().length, 3);
  assert.equal(audits().length, 1);
  assert.equal(await consent.isChecked(), false);
  assert(await confirm.isDisabled());
  await consent.check();
  await confirm.click();
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(entries().length, 3);
  assert.equal(audits().length, 1);
  assert.deepEqual(entries()[0], original);
  assert(entries().slice(1).every(e => e.motivo === reason));
  check('lost correction response retries without duplicating approval or entries and preserves the original');

  await open.click();
  await change(250, 'QA segunda correccion revisada');
  await api('/api/transacciones/' + doc.id, { notas: 'QA soporte recibido durante revision' }, 'PUT');
  await consent.check();
  await confirm.click();
  await dialog.getByRole('alert').waitFor();
  assert((await dialog.getByRole('alert').innerText()).includes('documento cambio'));
  assert.equal(entries().length, 3);
  assert.equal(await consent.isChecked(), false);
  await dialog.getByRole('button', { name: 'Actualizar documento', exact: true }).click();
  await confirm.waitFor();
  assert.equal(await dialog.getByLabel('Motivo de la correcci\u00f3n', { exact: true }).inputValue(), '');
  assert(await confirm.isDisabled());
  await change(250, 'QA segunda correccion revisada');
  await consent.check();
  await confirm.click();
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(entries().length, 5);
  assert.equal(audits().length, 2);
  await row.getByRole('button', { name: 'Traz.', exact: true }).click();
  const auditDialog = page.getByRole('dialog', { name: 'Trazabilidad de transacci\u00f3n', exact: true });
  await auditDialog.getByText('QA segunda correccion revisada', { exact: false }).first().waitFor();
  assert((await auditDialog.innerText()).includes('Responsable: Administrador CPA'));
  const changesTable = auditDialog.getByRole('table', { name: 'Detalle de la correcci\u00f3n', exact: true });
  assert.equal(await changesTable.count(), 2);
  assert.match(await changesTable.nth(0).innerText(), /Base\s+100\s+200/);
  assert.match(await changesTable.nth(1).innerText(), /Base\s+200\s+250/);
  await page.screenshot({ path: path.join(out, 'correccion-trazabilidad.png') });
  await auditDialog.getByRole('button', { name: 'Cerrar', exact: true }).click();
  check('stale review is rejected; refresh requires new consent and traceability shows both reasons and responsible CPA');

  await page.getByRole('button', { name: 'Contabilidad', exact: true }).click();
  await page.locator('input[type="month"]').fill('2025-03');
  await page.getByText('QA segunda correccion revisada', { exact: true }).first().waitFor();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'CSV', exact: true }).click();
  const download = await pending;
  const csvPath = path.join(out, 'correcciones.csv');
  await download.saveAs(csvPath);
  const csv = fs.readFileSync(csvPath, 'utf8');
  assert(csv.includes('motivo') && csv.includes(reason) && csv.includes('QA segunda correccion revisada'));
  check('published journal and CSV show the reasons for each correction');
};
