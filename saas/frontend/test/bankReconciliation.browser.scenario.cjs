const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { randomUUID } = require('node:crypto');

module.exports = async function bankBrowser({ page, api, client, account, period, out, bankKeys }) {
  await page.setViewportSize({width:1440,height:1050});
  const other=await api('/api/clientes',{nombre:'QA Otra empresa del navegador',ruc:'QA-UI-BANK-B',tipo:'natural'});
  const foreignAccount=await api('/api/cuentas-bancarias',{cliente_id:other.id,nombre:'Otra empresa',banco:'Banco General',numero:'999900001111',tipo:'corriente',moneda:'USD',idempotencia:randomUUID()});
  await api('/api/movimientos-bancarios',{cliente_id:other.id,cuenta_bancaria_id:foreignAccount.id,idempotencia:randomUUID(),fecha:period+'-06',descripcion:'BANCO EMPRESA AJENA',
    monto:400,tipo:'credito',banco:'Banco General'});
  await page.getByRole('button',{name:'Conciliación',exact:true}).click();
  await page.getByLabel('Cliente de conciliación').selectOption(client.id);
  await page.getByRole('tab',{name:'Cuentas bancarias',exact:true}).click();
  await page.getByRole('button',{name:'Registrar cuenta',exact:true}).click();
  const accountDialog=page.getByRole('dialog');
  assert.equal(await accountDialog.getByLabel('Cliente de la cuenta').inputValue(),client.id);
  await accountDialog.getByLabel('Nombre de la cuenta').fill('Reserva de operaciones UI');
  await accountDialog.getByLabel('Número de cuenta').fill('0001-0002-5678');
  await accountDialog.getByLabel('Tipo de cuenta').selectOption('ahorros');
  await page.setViewportSize({width:390,height:844});
  assert(await accountDialog.evaluate(el=>el.scrollWidth<=el.clientWidth));
  await page.screenshot({path:path.join(out,'cuenta-registro-mobile.png')});
  await accountDialog.getByRole('button',{name:'Guardar cuenta',exact:true}).click();
  await accountDialog.waitFor({state:'hidden'});
  const second=(await api('/api/cuentas-bancarias?cliente_id='+client.id)).data.find(a=>a.nombre==='Reserva de operaciones UI');
  assert(second);assert.equal(second.numero,'000100025678');
  await page.setViewportSize({width:1440,height:1050});
  await page.getByLabel('Cuenta de conciliación').selectOption(second.id);
  await page.getByRole('table',{name:'Directorio de cuentas bancarias'}).getByRole('cell').filter({hasText:'***5678'}).waitFor();
  await page.getByRole('tab',{name:'Pendientes al corte',exact:true}).click();
  await page.getByRole('button',{name:'Movimiento banco',exact:true}).waitFor({state:'visible'});
  await page.getByRole('button',{name:'Movimiento banco',exact:true}).click();
  const dialog=page.getByRole('dialog');
  assert.equal(await dialog.getByLabel('Cliente del movimiento').inputValue(),client.id);
  assert.equal(await dialog.getByLabel('Cuenta del movimiento').inputValue(),second.id);
  await dialog.getByLabel('Fecha bancaria').fill(period+'-06');
  await dialog.getByLabel('Descripción bancaria').fill('QA movimiento creado en formulario');
  await dialog.getByLabel('Monto bancario').fill('25.50');
  await dialog.getByRole('button',{name:'Guardar movimiento',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert((await api('/api/movimientos-bancarios?cliente_id='+client.id)).data.some(m=>m.descripcion==='QA movimiento creado en formulario'&&Number(m.monto)===25.5));
  await page.getByRole('button',{name:'Importar banco',exact:true}).click();
  assert.equal(await dialog.getByLabel('Cuenta del extracto').inputValue(),second.id);
  const csv=dialog.getByLabel('Contenido CSV bancario');
  const before=(await api('/api/movimientos-bancarios?cliente_id='+client.id)).total;
  await csv.fill(period+'-07,"Descripcion, con coma",10,credito,Banco General,0001\n'+period+'-08,fila incompleta');
  await dialog.getByRole('button',{name:'Revisar lote',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  assert(await dialog.getByRole('button',{name:'Importar',exact:true}).isDisabled());
  assert.equal((await api('/api/movimientos-bancarios?cliente_id='+client.id)).total,before);
  const text='fecha,descripcion,monto,tipo,banco,referencia\n'+Array.from({length:52},(_,i)=>
    period+'-07,"UI-BANK-'+String(i+1).padStart(3,'0')+', con coma",10,credito,Banco General,'+String(i).padStart(5,'0')).join('\n');
  await csv.fill(text);
  await dialog.getByRole('button',{name:'Revisar lote',exact:true}).click();
  await dialog.getByRole('status').filter({hasText:'52 movimientos'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  const bounds=await dialog.boundingBox();
  await page.screenshot({path:path.join(out,'banco-importacion-mobile.png')});
  assert(bounds.x>=0&&bounds.x+bounds.width<=390);
  assert(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth));
  await dialog.getByRole('button',{name:'Importar',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal((await api('/api/movimientos-bancarios?cliente_id='+client.id)).total,before+52);
  assert(await csv.isDisabled());
  await page.reload();
  await page.getByRole('button',{name:'Conciliación',exact:true}).click();
  await page.getByRole('button',{name:'Importar banco',exact:true}).click();
  await dialog.getByRole('status').filter({hasText:'52 movimientos'}).waitFor();
  assert.equal(await dialog.getByLabel('Cuenta del extracto').inputValue(),second.id);
  assert(await dialog.getByLabel('Cuenta del extracto').isDisabled());
  await dialog.getByRole('button',{name:'Reintentar envío',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert.equal(bankKeys.length,2);assert.equal(bankKeys[0],bankKeys[1]);
  await page.setViewportSize({width:1440,height:1050});
  await page.getByLabel('Cliente de conciliación').selectOption(client.id);
  await page.getByLabel('Cuenta de conciliación').selectOption(second.id);
  await page.locator('label').filter({hasText:'UI-BANK-052'}).waitFor();
  assert.equal(await page.locator('label').filter({hasText:'BANCO EMPRESA AJENA'}).count(),0);
  const rows=(await api('/api/movimientos-bancarios?cliente_id='+client.id)).data;
  assert.equal(rows.length,before+52);
  assert(rows.some(r=>r.descripcion==='UI-BANK-052, con coma'&&r.referencia==='00051'));
  await page.getByRole('tab',{name:'Banco del período',exact:true}).click();
  const table=page.getByRole('table',{name:'Movimientos bancarios del periodo'});
  await table.getByRole('cell').filter({hasText:'UI-BANK-052, con coma'}).waitFor();
  await page.getByRole('button',{name:'12 meses',exact:true}).click();
  await table.getByRole('cell').filter({hasText:'UI-BANK-052, con coma'}).waitFor();
  await page.screenshot({path:path.join(out,'banco-anual-desktop.png')});
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar CSV',exact:true}).click();
  const download=await downloadEvent;
  const csvPath=path.join(out,'banco-anual-export.csv');await download.saveAs(csvPath);
  const exported=fs.readFileSync(csvPath,'utf8');
  assert(exported.includes('UI-BANK-052'));assert(!exported.includes('BANCO EMPRESA AJENA'));
  assert(exported.includes('saldo_verificado'));assert(exported.includes(client.id));
  assert(exported.includes('***5678'));assert(exported.includes(second.id));assert(!exported.includes('***1234'));
  await page.getByLabel('Cuenta de conciliación').selectOption(account.id);
  await table.getByRole('cell').filter({hasText:'QA deposito de abono'}).waitFor();
  assert.equal(await table.getByRole('cell').filter({hasText:'UI-BANK-052, con coma'}).count(),0);
  await page.getByLabel('Cuenta de conciliación').selectOption(second.id);
  await page.getByRole('tab',{name:'Cuentas bancarias',exact:true}).click();
  await page.getByRole('button',{name:'Archivar',exact:true}).click();
  await dialog.getByLabel('Motivo del estado de cuenta').fill('Cuenta de reserva archivada en revision de prueba');
  await dialog.getByRole('button',{name:'Confirmar estado',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert.equal((await api('/api/cuentas-bancarias?cliente_id='+client.id)).data.find(a=>a.id===second.id).activa,false);
  await page.getByRole('button',{name:'Reactivar',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'cuentas-directorio-desktop.png')});
  await page.getByRole('tab',{name:'Banco del período',exact:true}).click();
  await page.getByLabel('Cliente de conciliación').selectOption(other.id);
  await table.getByRole('cell').filter({hasText:'BANCO EMPRESA AJENA'}).waitFor();
  assert.equal(await table.getByRole('cell').filter({hasText:'UI-BANK-052, con coma'}).count(),0);
  console.log('PASS bank browser: account creation/archive, exact-account filters, quoted CSV review, invalid batch, lost response/reload/same-key retry, 52 rows, annual export and mobile dialogs');
};
